    lines.append("")

    # 城市清单
    cities = [e for e in r["entities"] if e["type"] == "city"]
    if cities:
        lines.append("## 二、城市清单")
        lines.append("")
        lines.append("| code | name | parent | desc_short | metrics |")
        lines.append("|---|---|---|---|---|")
