    lines.append(f"- **表清单**:{', '.join(r['tables_list'])}")
    lines.append("")

    # 总览
    lines.append("## 一、Entity 总览")
    lines.append("")
    lines.append(f"| 类型 | 数量 |")
    lines.append(f"|---|---|")
    lines.append(f"| city(城市) | {r['city_count']} |")
    lines.append(f"| company(公司) | {r['company_count']} |")
